#!/usr/bin/env node
// Regenerates src/bot-ua-patterns.js from the crawler-user-agents upstream
// list (Issue #240). The committed data file is generated output and is
// never hand-edited; refresh the snapshot by running:
//
//   node scripts/update-bot-ua-patterns.mjs [crawler-user-agents.json]
//
// Without an argument the list is fetched from upstream master. Every
// pattern must compile as a JavaScript RegExp (wrapped in a non-capturing
// group, the form src/bot-detection.js consumes) — one invalid pattern
// fails the script loudly instead of shipping a broken combined regex.
import { readFileSync, writeFileSync } from "node:fs";

const UPSTREAM_URL = "https://raw.githubusercontent.com/monperrus/crawler-user-agents/master/crawler-user-agents.json";
const OUT_FILE = new URL("../src/bot-ua-patterns.js", import.meta.url);

const arg = process.argv[2];
const raw = arg
  ? readFileSync(arg, "utf8")
  : await (await fetch(UPSTREAM_URL)).text();
const entries = JSON.parse(raw);

const seen = new Set();
const patterns = [];
for (const entry of entries) {
  if (typeof entry.pattern !== "string" || entry.pattern === "") {
    throw new Error(`entry without a pattern field: ${JSON.stringify(entry).slice(0, 120)}`);
  }
  new RegExp(`(?:${entry.pattern})`); // throws on a pattern JS cannot compile
  // Upstream patterns are Python regexes, where \digit is always a
  // backreference. Combined into one alternation the group numbering shifts
  // per branch, so such a pattern would silently bind to the wrong group
  // instead of failing to compile (src/bot-detection.js relies on its
  // absence).
  if (/\\\d/.test(entry.pattern)) {
    throw new Error(`backreference pattern cannot be combined safely: ${entry.pattern.slice(0, 80)}`);
  }
  if (!seen.has(entry.pattern)) {
    seen.add(entry.pattern);
    patterns.push(entry.pattern);
  }
}

const snapshot = new Date().toISOString().slice(0, 10);
const body = `// Generated by scripts/update-bot-ua-patterns.mjs — do not edit by hand.
// Verbatim \`pattern\` fields of crawler-user-agents
// (https://github.com/monperrus/crawler-user-agents, MIT license),
// snapshot ${snapshot}: ${patterns.length} patterns, upstream order, deduplicated.
export const CRAWLER_UA_PATTERNS = [
${patterns.map((p) => `  ${JSON.stringify(p)},`).join("\n")}
];
`;

writeFileSync(OUT_FILE, body);
console.log(`wrote ${OUT_FILE.pathname}: ${patterns.length} patterns, ${body.length} bytes, snapshot ${snapshot}`);
